"""Generate the Rust catalogue from exact independently exported f32 words."""
import json
from pathlib import Path
root=Path(__file__).parent
data=json.loads((root/'catalogue.json').read_text())
assert data['commit']=='f050371a6cda83b9887eeb83a1884336fce28e53'
def array(xs):return '['+', '.join(map(str,xs))+']'
def floats(xs):return '['+', '.join(f'f32::from_bits(0x{x:08x})' for x in xs)+']'
def region(r):
    return 'LevelRegion { bounds: PositionBounds { region: '+str(r['index'])+', min: '+floats(r['min_bits'])+', max: '+floats(r['max_bits'])+' }, axis_bits: '+array(r['axis_bits'])+' }'
out=['// Generated by fixtures/levels-v41/generate_catalogue.py; do not edit.','use super::{LevelCalibration, LevelRegion, PositionBounds};','#[rustfmt::skip]','pub(super) const LEVELS: &[LevelCalibration] = &[']
for l in data['levels']:
    api = 'None' if l['api_id'] is None else 'Some(uuid::Uuid::from_bytes_le('+array(l['api_id'])+'))'
    display = 'None' if l['display_name'] is None else 'Some('+json.dumps(l['display_name'])+')'
    out += ['    LevelCalibration {',f'        tag: 0x{l["tag"]:08x}, structure_tag: 0x{l["structure_tag"]:08x}, module: "{l["module"]}", display_name: {display}, api_id: {api}, index_bits: {l["index_bits"]},','        play: '+region(l['regions'][0])+',','        others: &['+', '.join(region(r) for r in l['regions'][1:])+'],','    },']
out+= ['];','']
target=root.parent.parent/'film/catalog/maps/levels/data.rs';target.parent.mkdir(exist_ok=True);target.write_text('\n'.join(out))
