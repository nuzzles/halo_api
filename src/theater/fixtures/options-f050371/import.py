"""Import the pinned f050371 Options catalogue as the sole supported options data."""
import hashlib
from pathlib import Path
import subprocess
import sys

SOURCE = Path(sys.argv[1]) / "src/game/options_data.rs"
TARGET = Path(__file__).resolve().parents[2] / "film/catalog/options/data.rs"
EXPECTED = "021e911b805a2b74c24321c7209462a76bd0a708"
raw = SOURCE.read_bytes()
actual = hashlib.sha1(f"blob {len(raw)}\0".encode() + raw).hexdigest()
if actual != EXPECTED:
    raise SystemExit(f"unexpected source blob: {actual}")
source = raw.decode().replace(
    "// Generated from the game's files. Do not edit by hand.",
    "// Generated by fixtures/options-f050371/import.py; do not edit.",
)
source = source.replace("use super::options::", "use super::")
TARGET.write_text(source)
subprocess.run(["rustfmt", "--edition", "2024", str(TARGET)], check=True)
