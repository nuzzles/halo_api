#!/usr/bin/env python3
"""Import pinned catalogue data, optionally to an alternate catalog directory.

The independent oracle is export_reference.py, which executes original APIs.
This importer only adapts module paths, serde and explicit revision selection.
"""
import hashlib
from pathlib import Path
import subprocess
import sys

SOURCE = Path(sys.argv[1])
FILM = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[2] / "film" / "catalog"
BLOBS = {
    "medals_data.rs": "8d0e40d3b075e215b94614aa43bcafbc97554f1c",
    "options_data.rs": "021e911b805a2b74c24321c7209462a76bd0a708",
}
for name, expected in BLOBS.items():
    raw = (SOURCE / "src/game" / name).read_bytes()
    actual = hashlib.sha1(b"blob " + str(len(raw)).encode() + b"\0" + raw).hexdigest()
    if actual != expected:
        raise SystemExit(f"unexpected source blob for {name}: {actual}")
    text = raw.decode()
    text = text.replace("// Generated from the game's files. Do not edit by hand.",
        "// Generated by fixtures/game-catalogues-v41/generate_data.py; do not edit.")
    module = name.removesuffix("_data.rs")
    text = text.replace(f"use super::{module}::", "use super::")
    if module == "medals":
        text = text.replace('#[cfg_attr(feature = "serde", serde(rename_all = "snake_case"))]', '#[serde(rename_all = "snake_case")]')
        text = text.replace('#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]',
            '#[derive(serde::Serialize, serde::Deserialize)]')
        text = text.replace("Its discriminant is the game's medal index, the value films carry.",
            "Its discriminant is the reference medal index, not a service NameId.")
        text = text.replace("pub fn from_index(index: u32)", "pub(super) fn lookup(index: u32)")
    target = FILM / module / "data.rs"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    subprocess.run(["rustfmt", "--edition", "2024", str(target)], check=True)
