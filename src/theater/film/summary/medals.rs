// Keep the measured type/code table in one place for both decoding and ID lookup.
macro_rules! known_medals {
    ($(($type_code:literal, $medal_code:literal) => $name:ident,)*) => {
        impl Medal {
            /// Resolve only a measured pair; never fall back to a neighboring code.
            pub fn from_codes(type_code: u8, medal_code: u8) -> Self {
                match (type_code, medal_code) {
                    $(($type_code, $medal_code) => Self::$name,)*
                    _ => Self::Unknown { type_code, medal_code },
                }
            }

            /// Raw medal code recorded in the film summary.
            pub fn code(self) -> u8 {
                match self {
                    $(Self::$name => $medal_code,)*
                    Self::Unknown { medal_code, .. } => medal_code,
                }
            }
        }
    };
}

