impl std::fmt::Display for Medal {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        if let Some(name) = self.name() {
            return formatter.write_str(name);
        }
        match self {
            Self::Unknown {
                type_code,
                medal_code,
            } => write!(formatter, "unknown medal ({type_code}, {medal_code})"),
            _ => unreachable!("known medals have names"),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::Medal;

    #[test]
    fn every_decoded_medal_retains_its_recorded_code() {
        for type_code in u8::MIN..=u8::MAX {
            for medal_code in u8::MIN..=u8::MAX {
                assert_eq!(Medal::from_codes(type_code, medal_code).code(), medal_code);
            }
        }
        assert_eq!(Medal::from_codes(50, 156), Medal::Splatter);
        assert_eq!(
            Medal::from_codes(77, 251),
            Medal::Unknown {
                type_code: 77,
                medal_code: 251,
            }
        );
    }
}
